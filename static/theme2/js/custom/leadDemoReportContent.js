function getLeadDemoReportRowHtml(reportRows, page, pageSize) {
    if (!reportRows || reportRows.length === 0) {
        return '<tr><td colspan="17" class="text-center">No records found</td></tr>';
    }

    var startDate1 = ($('#leadDemoReportStartDate').val() || '')
    var endDate1 = ($('#leadDemoReportEndDate').val() || '')
    var startDate=startDate1.split("-")[2]+'-'+startDate1.split("-")[1]+'-'+startDate1.split("-")[0];
	var endDate=endDate1.split("-")[2]+'-'+endDate1.split("-")[1]+'-'+endDate1.split("-")[0];
    var rowHtml = '';
    $.each(reportRows, function(index, item) {
        var urlClick="/dashboard/lead-data-list?moduleId=" + moduleId +"&leadId=0&leadFrom=LEAD&currentPage=0&euid=" +ENCRYPTED_USER_ID + "&leadType=B2C";
        var demoLeadLink="clickLeadsLink('"+urlClick+"','"+startDate+"', '"+endDate+"','demoLead-"+item.demoAssignUserId+"-demo','', '')";
        var rowNumber = (page * pageSize) + index + 1;
        rowHtml += '<tr>'
            + '<td>' + rowNumber + '</td>'
            + '<td>' + (item.counselorName || 'N/A') + '</td>'
            + '<td class="text-center"><a href="javascript:void(0);" onclick="' + demoLeadLink + '">' + (item.totalDemo || 0) + '</a></td>'
            + '<td class="text-center">' + (item.demoDone || 0) + '</td>'
            + '<td class="text-center">' + (item.demoNotDone || 0) + '</td>'
            + '<td class="text-center">' + (item.noStatusUpdate || 0) + '</td>'
            + '<td class="text-center">' + (item.statusUpdated || 0) + '</td>'
            + '<td class="text-center">' + (item.hostNotJoin || 0) + '</td>'
            + '<td class="text-center">' + (item.attendeeNotJoin || 0) + '</td>'
            + '<td class="text-center">' + (item.attendeeBeforeClick || 0) + '</td>'
             + '<td class="text-left">' + (item.totalMeetingDuration || 0) + '</td>'
            + '<td class="text-left">' + (item.hostJoinWaitingForAttendeeAvg || '') + '</td>'
            + '<td class="text-left">' + (item.responseTimeAvg || '') + '</td>'
            + '<td class="text-center">' + (item.userWiseDemoDone || 0) + '</td>'
            + '<td class="text-center">' + (item.cancelledDemo || 0) + '</td>'
            + '<td class="text-center">' + (item.notShowDemo || 0) + '</td>'
            + '<td class="text-center">' + (item.demoConfirm || 0) + '</td>'
            + '<td class="text-center">' + (item.demoNotConfirm || 0) + '</td>'
            + '<td class="text-center">' + (item.rescheduleDemo || 0) + '</td>'
        + '</tr>';
    });
    return rowHtml;
}
